// NaN → Not a Number
// It means the result is not a valid number.

let result = "hello" / 2;

// "hello" cannot be divided by 2,
// so JavaScript gives us NaN.

console.log(result); // NaN


// Another example
let answer = 0 / 0;

// 0 divided by 0 is not a valid number,
// so the result is NaN.

console.log(answer); // NaN