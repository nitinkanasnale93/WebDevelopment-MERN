// let → value can be changed

let age = 23;
age = 24;

console.log(age); // 24


// const → value cannot be changed

const pi = 3.14;

// pi = 3.15; // Error

console.log(pi); // 3.14


// var → older way of declaring variables

var name = "Nitin";
name = "Rahul";

console.log(name); // Rahul

// var → old syntax for declaring variables

var oldAge = 23;
var cgpa = 8.9;

var num1 = 1;
var num2 = 2;

var sum = num1 + num2;

console.log(oldAge); // 23
console.log(cgpa);  // 8.9
console.log(sum);   // 3