// String Index → each character has an index
// Index starts from 0

let name = "TONY STARK";

console.log(name[0]); // T
console.log(name[1]); // O
console.log(name[2]); // N

console.log(name[name.length - 1]); // K

console.log(name.length); // 10


// Concatenation → adding strings together

console.log("tony" + " " + "stark");
// tony stark

console.log("tony" + 1);
// tony1